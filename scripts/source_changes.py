#!/usr/bin/env python3
"""Write docs/SOURCE-CHANGES.md: every text that changed while sources were added (published
version from git HEAD -> current research files), and every statement marked uncertain.
Usage: python3 scripts/source_changes.py [git revision, default: the last published version]"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REV = sys.argv[1] if len(sys.argv) > 1 else "7965a15"
FILES = [("research/central.json", "canton"), ("research/northeast.json", "canton"), ("research/northwest.json", "canton"),
         ("research/west.json", "canton"), ("research/south.json", "canton"), ("research/helvetic.json", "helvetic"),
         ("research/allies.json", "allies"), ("research/stories-lords.json", "story"), ("research/stories-wars.json", "story"),
         ("research/stories-reformation.json", "story"), ("research/sources-content.json", "content")]


def old_version(path):
    try:
        return json.loads(subprocess.check_output(["git", "show", "%s:%s" % (REV, path)], cwd=ROOT, stderr=subprocess.DEVNULL))
    except Exception:
        return None


def step_lines(sa, sb, label):
    out = []
    if sa and sa.get("title") != sb.get("title"):
        out.append("- **%s** — title: %s → %s" % (label, sa.get("title"), sb.get("title")))
    ta, tb = (sa or {}).get("text", []), sb.get("text", [])
    for i in range(max(len(ta), len(tb))):
        a = ta[i] if i < len(ta) else "(none)"
        b = tb[i] if i < len(tb) else "(removed)"
        if a != b:
            out.append("- **%s** — old: %s\n  - new: %s" % (label, a, b))
    for u in sb.get("uncertain", []):
        out.append("- **%s** — uncertain: %s" % (label, u))
    return out


def main():
    out = ["# Changes made while adding sources", "",
           "Every text that changed when the sources were checked (old → new), and every statement now marked uncertain.",
           "Generated by scripts/source_changes.py, comparing the published version (%s) with the sourced research files." % REV, ""]
    for path, kind in FILES:
        full = os.path.join(ROOT, path)
        if not os.path.exists(full):
            continue
        new, old = json.load(open(full, encoding="utf-8")), old_version(path)
        if kind == "canton" or kind == "story":
            olds = {x.get("canton") or x.get("id"): x for x in (old or [])}
            for b in new:
                key = b.get("canton") or b.get("id")
                a = olds.get(key, {"stops": []})
                lines = []
                for i, sb in enumerate(b["stops"]):
                    sa = a["stops"][i] if i < len(a["stops"]) else None
                    lines += step_lines(sa, sb, sb.get("tick") or sb.get("year"))
                if lines:
                    out += ["## %s" % (b.get("name") or b.get("title")), ""] + lines + [""]
        elif kind == "helvetic":
            lines = []
            for i, sb in enumerate(new["stops"]):
                sa = old["stops"][i] if old and i < len(old["stops"]) else None
                lines += step_lines(sa, sb, sb.get("date") or sb.get("year"))
            if lines:
                out += ["## Helvetic cantons", ""] + lines + [""]
        elif kind == "allies":
            olds = {x["id"]: x for x in (old or [])}
            lines = []
            for b in new:
                a = olds.get(b["id"], {})
                for f in ("name", "label", "from", "until"):
                    if a and a.get(f) != b.get(f):
                        lines.append("- **%s** — %s: %s → %s" % (b["id"], f, a.get(f), b.get(f)))
                for u in b.get("uncertain", []):
                    lines.append("- **%s** — uncertain: %s" % (b["id"], u))
            if lines:
                out += ["## Allies", ""] + lines + [""]
        elif kind == "content":
            lines = []
            for k, v in new.items():
                for u in v.get("uncertain", []):
                    lines.append("- **%s** — uncertain: %s" % (k, u))
                if v.get("changed"):
                    lines.append("- **%s** — text changed: %s" % (k, v["changed"]))
            if lines:
                out += ["## Main map, 1803 and Bern stories", ""] + lines + [""]
    open(os.path.join(ROOT, "docs", "SOURCE-CHANGES.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(sum(1 for l in out if l.startswith("- ")), "entries")


if __name__ == "__main__":
    main()
